-- Initial schema for a new Supabase project. Run in the SQL Editor.
begin;
create table public.occasions (
  id bigint generated by default as identity primary key,
  name text not null, date date not null, description text not null,
  category text, created_at timestamptz not null default now()
);
create table public.media (
  id bigint generated by default as identity primary key,
  occasion_id bigint not null references public.occasions on delete cascade,
  type text not null, url text, youtube_link text
);
create table public.receipts (
  id bigint generated by default as identity primary key,
  donor_name text not null, amount numeric(12,2) not null check (amount > 0),
  purpose text, via text, contact text, date date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.occasions enable row level security;
alter table public.media enable row level security;
alter table public.receipts enable row level security;
grant select on public.occasions, public.media to anon, authenticated;
grant select, insert, update, delete on public.occasions, public.media, public.receipts to authenticated;
grant usage on sequence public.occasions_id_seq, public.media_id_seq, public.receipts_id_seq to authenticated;

create policy "Public calendar" on public.occasions for select using (true);
create policy "Public event media" on public.media for select using (true);
create policy "Donors read matching receipts" on public.receipts for select to authenticated
using (lower(trim(contact)) = lower(auth.jwt()->>'email'));
create policy "Trust owner manages occasions" on public.occasions for all to authenticated
using (auth.jwt()->'app_metadata'->>'role' = 'owner')
with check (auth.jwt()->'app_metadata'->>'role' = 'owner');
create policy "Trust owner manages media" on public.media for all to authenticated
using (auth.jwt()->'app_metadata'->>'role' = 'owner')
with check (auth.jwt()->'app_metadata'->>'role' = 'owner');
create policy "Trust owner manages receipts" on public.receipts for all to authenticated
using (auth.jwt()->'app_metadata'->>'role' = 'owner')
with check (auth.jwt()->'app_metadata'->>'role' = 'owner');

insert into storage.buckets (id, name, public) values ('media', 'media', true);
create policy "Trust owner uploads event files" on storage.objects for insert to authenticated
with check (bucket_id = 'media' and auth.jwt()->'app_metadata'->>'role' = 'owner');
commit;
